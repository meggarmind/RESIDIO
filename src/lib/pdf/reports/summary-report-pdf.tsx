import { Document, Page, Text, View } from '@react-pdf/renderer';
import { reportPdfStyles as s } from '@/lib/pdf/reports/base-styles';
import { formatCalendarDate } from '@/lib/utils/calendar-date';
import { MAX_SUMMARY_TILES, formatSummaryCell, type SummaryReportData } from '@/lib/reports/summary-report';

/**
 * Server PDF for a summary-first report (#1399): tiles, the bars as a labelled bar list, then the
 * table. Landscape, because the table can have ten columns. The screen layout is
 * `@/components/reports/summary-report-layout`.
 */

const WIDE_COLUMNS = new Set(['debtor', 'contact']);

export function SummaryReportPdf({ data, title, estateName }: { data: SummaryReportData; title: string; estateName: string }) {
  const { summary, chart, table, notes } = data;
  const max = chart ? Math.max(0, ...chart.bars.map((b) => Math.abs(b.value))) : 0;
  const flexFor = (key: string) => (WIDE_COLUMNS.has(key) ? 3 : 2);

  return (
    <Document>
      <Page size="A4" orientation="landscape" style={s.page}>
        <View style={s.header}>
          <View style={s.headerRow}>
            <View><Text style={s.headerTitle}>{title}</Text></View>
            <View style={s.headerRight}>
              <Text style={s.headerRightTitle}>{estateName}</Text>
              <Text style={s.headerRightDate}>{formatCalendarDate(new Date(), 'en-GB', { day: '2-digit', month: 'long', year: 'numeric' })}</Text>
            </View>
          </View>
        </View>

        <View style={s.section}>
          <View style={s.summaryRow}>
            {summary.slice(0, MAX_SUMMARY_TILES).map((tile, i) => (
              <View key={i} style={s.summaryBox}>
                <Text style={s.summaryLabel}>{tile.label}</Text>
                <Text style={[s.summaryValue, tile.tone === 'bad' ? s.amountNegative : {}, tile.tone === 'good' ? s.amountPositive : {}]}>{formatSummaryCell(tile.value)}</Text>
                {tile.hint ? <Text style={s.summaryLabel}>{tile.hint}</Text> : null}
              </View>
            ))}
          </View>
        </View>

        {chart && (
          <View style={s.section}>
            <Text style={s.sectionTitle}>{chart.title}</Text>
            {chart.bars.map((bar, i) => (
              <View key={i} style={{ flexDirection: 'row', alignItems: 'center', marginBottom: 4 }}>
                <Text style={[s.tableCell, { width: 90 }]}>{bar.label}</Text>
                <View style={{ flex: 1, height: 8, backgroundColor: '#eeeeee' }}>
                  <View style={{ height: 8, width: `${max > 0 ? (Math.abs(bar.value) / max) * 100 : 0}%`, backgroundColor: bar.tone === 'good' ? '#16a34a' : bar.tone === 'bad' ? '#dc2626' : '#6366f1' }} />
                </View>
                <Text style={[s.tableCell, s.amountRight, { width: 90 }]}>{bar.display ?? formatSummaryCell(bar.value)}</Text>
              </View>
            ))}
          </View>
        )}

        <View style={s.table}>
          <View style={s.tableHeader} fixed>
            {table.columns.map((col) => (
              <Text key={col.key} style={[s.tableHeaderCell, col.align === 'right' ? s.amountRight : {}, { flex: flexFor(col.key) }]}>{col.label}</Text>
            ))}
          </View>
          {table.rows.map((row, i) => (
            <View key={i} style={[s.tableRow, i % 2 === 1 ? s.tableRowAlt : {}]} wrap={false}>
              {table.columns.map((col) => (
                <Text key={col.key} style={[s.tableCell, col.align === 'right' ? s.amountRight : {}, { flex: flexFor(col.key) }]}>{formatSummaryCell(row[col.key])}</Text>
              ))}
            </View>
          ))}
          {table.totals && (
            <View style={[s.tableRow, { backgroundColor: '#f5f5f5' }]} wrap={false}>
              {table.columns.map((col) => (
                <Text key={col.key} style={[s.tableCell, s.amountBold, col.align === 'right' ? s.amountRight : {}, { flex: flexFor(col.key) }]}>{formatSummaryCell(table.totals![col.key])}</Text>
              ))}
            </View>
          )}
        </View>

        {notes?.map((note, i) => (
          <Text key={i} style={[s.tableCell, { marginTop: 8, color: '#666' }]}>{note}</Text>
        ))}
        <Text style={s.footer}>Generated by {estateName} — {title}</Text>
      </Page>
    </Document>
  );
}
