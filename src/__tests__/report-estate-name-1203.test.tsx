import React from 'react';
import { describe, expect, it } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import { CollectionReportPdf } from '@/lib/pdf/reports/collection-report-pdf';
import { FinancialOverviewPdf } from '@/lib/pdf/reports/financial-overview-pdf';
import { InvoiceAgingPdf } from '@/lib/pdf/reports/invoice-aging-pdf';
import {
  DebtorsReportPdf,
  DevelopmentLevyPdf,
  IndebtednessReportPdf,
  TransactionLogPdf,
} from '@/lib/pdf/reports/reference-reports-pdf';
import { ScheduledReportEmail } from '@/emails/scheduled-report';

// Report PDFs are pure function components: walk the element tree they return and collect
// text, with no PDF rendering. Any field the PDF reads is an empty list that also acts as
// the number 0 (and has the Number methods), so no per-report fixture is needed.
const zero = Number(0);
const emptyData: unknown = new Proxy([] as unknown[], {
  get: (target, key) => {
    if (key === Symbol.toPrimitive) return () => 0;
    if (key === 'valueOf') return () => 0;
    if (key === 'toString') return () => '0';
    if (key in target) return Reflect.get(target, key);
    if (key in Number.prototype) return (Number.prototype as never)[key as never] && ((...a: unknown[]) => (zero as never as Record<string, (...x: unknown[]) => unknown>)[key as string](...a));
    return emptyData;
  },
});

function collectText(node: React.ReactNode): string[] {
  if (node == null || typeof node === 'boolean') return [];
  if (typeof node === 'string' || typeof node === 'number') return [String(node)];
  if (Array.isArray(node)) return node.flatMap(collectText);
  const el = node as React.ReactElement<{ children?: React.ReactNode }>;
  if (typeof el.type === 'function') {
    return collectText((el.type as (p: unknown) => React.ReactNode)(el.props));
  }
  return collectText(el.props?.children);
}

const ESTATE = 'Palm Grove Estate';

const reports: Array<[string, (p: { data: never; estateName: string }) => React.ReactElement, string]> = [
  ['collection report', CollectionReportPdf as never, 'Collection Report'],
  ['financial overview', FinancialOverviewPdf as never, 'Financial Overview Report'],
  ['invoice aging', InvoiceAgingPdf as never, 'Invoice Aging Report'],
  ['transaction log', TransactionLogPdf as never, 'Transaction Log'],
  ['debtors report', DebtorsReportPdf as never, 'Debtors Report'],
  ['indebtedness report', IndebtednessReportPdf as never, 'Indebtedness Report'],
  ['development levy', DevelopmentLevyPdf as never, 'Development Levy Report'],
];

describe('report PDFs name the estate (#1203)', () => {
  it.each(reports)('%s uses the estate name in header and footer', (_name, Pdf, title) => {
    const text = collectText(Pdf({ data: emptyData as never, estateName: ESTATE }));
    expect(text).toContain(ESTATE);
    expect(text.join('')).toContain(`Generated by ${ESTATE} — ${title}`);
    expect(text.join(' ')).not.toMatch(/Residio/);
  });
});

describe('ScheduledReportEmail (#1203)', () => {
  it('names the report, the period and the estate', () => {
    const html = renderToStaticMarkup(
      <ScheduledReportEmail
        estateName={ESTATE}
        reportLabel="Financial Overview"
        periodLabel="01 Sep 2026 to 30 Sep 2026"
      />,
    );
    expect(html).toContain('Financial Overview');
    expect(html).toContain('01 Sep 2026 to 30 Sep 2026');
    expect(html).toContain(ESTATE);
  });

  it('omits the period line when there is none', () => {
    const html = renderToStaticMarkup(<ScheduledReportEmail estateName={ESTATE} reportLabel="Invoice Aging Report" />);
    expect(html).not.toContain('Period covered');
  });
});
